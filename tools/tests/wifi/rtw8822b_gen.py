#!/usr/bin/env python3
# Expected results for tools/tests/wifi/rtw8822b_main.c, computed straight from the Linux rtw88 source
# (rtw_parse_tbl_phy_cond semantics) so the converted tables and the C walker are checked independently.
import re, sys
src = open(sys.argv[1]).read()
def arr(n):
    m = re.search(r'static const u32 ' + n + r'\[\] = \{(.*?)\};', src, re.S)
    return [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', m.group(1))]
def walk(v, cut, rfe, pkg=15, intf=1):
    def ok(c):
        cc, pk, it, rf = (c >> 24) & 15, (c >> 12) & 15, (c >> 8) & 15, c & 255
        if cc and cc != cut: return False
        if pk and pk != pkg: return False
        if it and it != intf: return False
        return rf == rfe
    pos, matched, skipped, n, ck = 0, True, False, 0, 0
    for i in range(0, len(v), 2):
        a, d = v[i], v[i + 1]
        if a >> 31:
            br = (a >> 28) & 3
            if br == 3: matched, skipped = True, False
            elif br == 2: matched = not skipped
            else: pos = a
        elif (a >> 30) & 1:
            if not skipped:
                if ok(pos): matched, skipped = True, True
                else: matched, skipped = False, False
            else: matched = False
        elif matched:
            n += 1
            ck = (ck * 31 + a * 7 + d) & 0xffffffff
    return n, ck
names = ['mac', 'agc', 'bb', 'rf_a', 'rf_b']
out = ['/* generated by rtw8822b_gen.py */', 'typedef struct { int tbl, cut, rfe, n; unsigned ck; } exp8b;', 'static const exp8b g_exp[] = {']
for ti, nm in enumerate(names):
    v = arr('rtw8822b_' + nm)
    for cut in (2, 3, 15):
        for rfe in (2, 3, 5):
            n, ck = walk(v, cut, rfe)
            out.append('  {%d,%d,%d,%d,0x%08Xu},' % (ti, cut, rfe, n, ck))
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
