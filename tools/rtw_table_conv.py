import re, sys
# Converts Linux rtw88 rtwXXXX_table.c (GPL-2.0 OR BSD-3-Clause) into the NoovexOS conditional table format:
# const unsigned int <prefix>_<name>[2N] (addr,data pairs incl. the 0x8/0x4/0x9.../0xA.../0xB... condition words)
# plus const int <prefix>_<name>_n = N, the same layout rtw_apply_cond walks.
# usage: rtw_table_conv.py <linux_table.c> <prefix> <out.c> <out.h> name[:3] ...   (":3" = 3-word dpk table, n = rows)
src = open(sys.argv[1]).read()
prefix, outc, outh = sys.argv[2], sys.argv[3], sys.argv[4]
names = sys.argv[5:]
hdr = src.split('\n')[0:3]
spdx = '\n'.join(hdr)
body_c = [spdx, '/* generated by tools/rtw_table_conv.py from Linux rtw88 */', '#include "drivers/net/wifi/rtw88/chips/%s"' % outh.split('/')[-1], '']
body_h = [spdx.replace('// SPDX', '/* SPDX').replace('Clause', 'Clause */', 1) if spdx.startswith('//') else spdx, '/* generated by tools/rtw_table_conv.py from Linux rtw88 */',
          '#ifndef %s_TABLES_H' % prefix.upper(), '#define %s_TABLES_H' % prefix.upper(), '']
MASKS = {'MASKDWORD': 0xffffffff, 'MASKHWORD': 0xffff0000, 'MASKLWORD': 0xffff, 'MASKBYTE0': 0xff,
         'MASKBYTE1': 0xff00, 'MASKBYTE2': 0xff0000, 'MASKBYTE3': 0xff000000, 'RFREG_MASK': 0xfffff, 'MASK20BITS': 0xfffff}
def tok(t):
    t = t.strip()
    t = re.sub(r'BIT\((\d+)\)', lambda m: str(1 << int(m.group(1))), t)
    t = re.sub(r'GENMASK\((\d+),\s*(\d+)\)', lambda m: str(((1 << (int(m.group(1)) + 1)) - 1) & ~((1 << int(m.group(2))) - 1)), t)
    for k, v in MASKS.items(): t = re.sub(r'\b%s\b' % k, str(v), t)
    if not re.fullmatch(r'[0-9a-fA-FxX|()\s]+', t): sys.exit('cannot parse token %r' % t)
    return eval(t) & 0xffffffff
total = 0
for spec in names:
    name, _, w = spec.partition(':'); w = int(w or 2)
    m = re.search(r'static const u32 %s_%s\[\] = \{(.*?)\};' % (prefix, name), src, re.S)
    if not m: sys.exit('table %s not found' % name)
    vals = [tok(t) for t in re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S).split(',') if t.strip()]
    if len(vals) % w: sys.exit('table %s: %d words not a multiple of %d' % (name, len(vals), w))
    n = len(vals) // w
    sym = '%s_%s' % (prefix, name)
    total += len(vals) * 4
    body_h.append('extern const unsigned int %s[%d];' % (sym, max(len(vals), 1)))
    body_h.append('extern const int %s_n;' % sym)
    lines = []
    for i in range(0, len(vals), 8):
        lines.append(' ' + ','.join('0x%X' % v for v in vals[i:i + 8]) + ',')
    if not vals: lines.append(' 0,')
    body_c.append('const unsigned int %s[%d]={' % (sym, max(len(vals), 1)))
    body_c += lines
    body_c.append('};')
    body_c.append('const int %s_n=%d;' % (sym, n))
    body_c.append('')
body_h += ['', '#endif', '']
open(outc, 'w').write('\n'.join(body_c))
open(outh, 'w').write('\n'.join(body_h))
print('%d tables, %d bytes of table data' % (len(names), total))
