import math, re, sys
src, out = sys.argv[1], sys.argv[2]
FL = {'DFS': 1, 'NO-IR': 2, 'PASSIVE-SCAN': 2, 'NO-IBSS': 2, 'NO-OUTDOOR': 4, 'AUTO-BW': 8, 'NO-INDOOR': 16}
rules, rix, ctry, cur = [], {}, [], None
for ln in open(src):
    ln = ln.split('#')[0].strip()
    m = re.match(r'country\s+(\w\w):\s*(\S*)', ln)
    if m:
        cur = [m.group(1), {'DFS-FCC': 1, 'DFS-ETSI': 2, 'DFS-JP': 3}.get(m.group(2), 0), []]; ctry.append(cur); continue
    m = re.match(r'\(\s*([\d.]+)\s*-\s*([\d.]+)\s*@\s*([\d.]+)\s*\)\s*,\s*\(\s*([\d.]+)\s*(mW)?\s*\)(.*)', ln)
    if not m or cur is None: continue
    lo, hi, bw = float(m.group(1)), float(m.group(2)), float(m.group(3))
    if lo > 7200: continue
    p = float(m.group(4)); dbm = int(math.floor(10 * math.log10(p) + 0.5)) if m.group(5) else int(p)
    f = 0
    for t in m.group(6).split(','):
        f |= FL.get(t.strip(), 0)
    r = (int(lo * 2), int(hi * 2), int(bw), dbm, f)
    if r not in rix: rix[r] = len(rules); rules.append(r)
    cur[2].append(rix[r])
o = ['#ifndef NVX_NET_WIFI_REGDB_DATA_H', '#define NVX_NET_WIFI_REGDB_DATA_H', '/* generated by tools/regdb/regdb_gen.py from wireless-regdb db.txt, ISC licence, see NOTICE */']
o.append('static const struct regdb_rule g_regdb_rules[%d]={' % len(rules))
o += ['{%d,%d,%d,%d,%d},' % r for r in rules]
o.append('};')
idx = []
o.append('static const u16 g_regdb_idx[]={')
for c in ctry:
    c.append(len(idx)); idx += c[2]
for i in range(0, len(idx), 24): o.append(','.join(map(str, idx[i:i + 24])) + ',')
o.append('};')
o.append('static const struct regdb_country g_regdb_ctry[%d]={' % len(ctry))
o += ['{"%s",%d,%d,%d},' % (c[0], c[1], c[3], len(c[2])) for c in ctry]
o.append('};')
o.append('#endif')
open(out, 'w').write('\n'.join(o) + '\n')
print(len(ctry), 'countries', len(rules), 'rules', len(idx), 'refs')
