#!/usr/bin/env python3
import re, sys, os
src = sys.argv[1]; out = sys.argv[2]
d = os.path.dirname(src)
t = open(src).read(); rg = open(os.path.join(d, 'regd.c')).read()
REGD = ['WW','ETSI','FCC','MKK','NA','IC','KCC','ACMA','NCC','MEXICO','CHILE','UKRAINE','CN','QATAR','UK','THAILAND','NZ','BR','AR']
NR = len(REGD)
def body(name):
    i = t.index(name); j = t.index('{', t.index('=', i)); k = t.index('\n};', j); return t[j+1:k]
def sparse(name, nidx):
    m = {}
    for g in re.finditer(r'((?:\[[A-Z0-9_]+\]){%d})\s*=\s*(-?\d+)' % nidx, body(name)):
        ix = [x for x in re.findall(r'\[([A-Z0-9_]+)\]', g.group(1))]
        ix = [REGD.index(x[6:]) if x.startswith('RTW89_') else int(x) for x in ix]
        m[tuple(ix)] = int(g.group(2))
    return m
def dense(m, dims, keep):
    vals = []
    def rec(pre, lv):
        if lv == len(dims):
            vals.append(m.get(tuple(pre), 0)); return
        for i in range(keep[lv] if keep[lv] is not None else dims[lv]): rec(pre + [i], lv + 1)
    rec([], 0); return vals
lines = ['/* SPDX-License-Identifier: GPL-2.0 OR BSD-3-Clause */',
 '/* Copyright(c) 2019-2020  Realtek Corporation */',
 '/* Generated by tools/rtw89/gen_txpwr_8852b.py from Linux rtw89 rtw8852b_table.c (txpwr_byrate, txpwr_lmt_2g/5g, txpwr_lmt_ru_2g/5g) and regd.c; used under BSD-3-Clause. */',
 '#ifndef NVX_RTW8852B_TXPWR_TBL_H', '#define NVX_RTW8852B_TXPWR_TBL_H']
byr = re.findall(r'\{\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(0x[0-9a-fA-F]+),\s*\}', body('rtw89_8852b_txpwr_byrate[]'))
lines.append('static const u32 rtw8852b_byr_cfg[%d][6]={' % len(byr))
lines += ['{%s,%s,%s,%s,%s,%s},' % b for b in byr]; lines.append('};')
def emit(name, cname, nidx, dims, keep):
    v = dense(sparse(name, nidx), dims, keep)
    lines.append('static const signed char %s[%d]={' % (cname, len(v)))
    for i in range(0, len(v), 40): lines.append(','.join(str(x) for x in v[i:i+40]) + ',')
    lines.append('};')
emit('rtw89_8852b_txpwr_lmt_2g[', 'rtw8852b_lmt_2g', 6, [2,2,3,2,NR,14], [None]*6)
emit('rtw89_8852b_txpwr_lmt_5g[', 'rtw8852b_lmt_5g', 6, [4,2,3,2,NR,53], [1,None,None,None,None,None])
emit('rtw89_8852b_txpwr_lmt_ru_2g[', 'rtw8852b_lmt_ru_2g', 4, [8,2,NR,14], [3,None,None,None])
emit('rtw89_8852b_txpwr_lmt_ru_5g[', 'rtw8852b_lmt_ru_5g', 4, [8,2,NR,53], [3,None,None,None])
cc = re.findall(r'COUNTRY_REGD\("([A-Z0-9]{2})",\s*RTW89_(\w+),\s*RTW89_(\w+),', rg[rg.index('rtw89_regd_map[]'):])
lines.append('static const char rtw8852b_cc_regd[]="' + ''.join(a + chr(65 + REGD.index(b)) + chr(65 + REGD.index(c)) for a, b, c in cc) + '";')
lines += ['#endif', '']
open(out, 'w').write('\n'.join(lines))
print(len(byr), len(cc))
