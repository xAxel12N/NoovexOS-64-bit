static void rtw_cx_link(rtw_cx_st* s){
    u8 b=s->lb2; s->prof_n=0; s->link=b&1;
    s->pan=s->link&&(b&0x80); s->a2dp=s->link&&(b&0x40); s->hid=s->link&&(b&0x20); s->hfp=s->link&&(b&0x02);
    s->prof_n=(u8)(s->pan+s->a2dp+s->hid+s->hfp);
    if(b&0x04)s->status=CX_BTS_INQ_PAGE; else if(!(b&1))s->status=CX_BTS_NCON_IDLE; else if(b==1)s->status=CX_BTS_CON_IDLE;
    else if(b&0x12)s->status=(b&0x08)?CX_BTS_ACL_SCO_BUSY:CX_BTS_SCO_BUSY; else if(b&0x08)s->status=CX_BTS_ACL_BUSY; else s->status=CX_BTS_CON_IDLE; }
static int rtw_cx_bt_info(rtw_cx_st* s,const u8* b,int len){
    if(len!=7||((b[0]&0xF)!=1&&(b[0]&0xF)!=2))return 0;
    if(s->have_info&&b[1]==s->lb2&&b[2]==s->lb3&&b[3]==s->hb0&&b[4]==s->hb1&&b[5]==s->hb2&&b[6]==s->hb3)return 0;
    s->have_info=1; s->lb2=b[1]; s->lb3=b[2]; s->hb0=b[3]; s->hb1=b[4]; s->hb2=b[5]; s->hb3=b[6];
    { u8 ip=(s->lb2&0x04)!=0; if(ip!=s->inq_page){ if(ip){ s->inq_remain=1; s->inq_fall=0; } else s->inq_fall=1; } }
    s->reinit=(u8)(s->reinit|((s->hb1&0x02)?1:0)); s->ign_off=(u8)(s->ign_off|(((s->hb1&0x08)&&!(s->hb1&0x04))?1:0));
    s->inq_page=(s->lb2&0x04)!=0; s->ble=(s->hb1&1)!=0; s->bt_page=(s->lb3&0x80)!=0; s->multi=(s->hb1&0x80)!=0;
    s->a2dp_active=(s->hb2&0x04)!=0; s->hid_slot=(u8)((s->hb2&0x30)>>4); s->hid_pair=(u8)((s->hb2&0xC0)>>6);
    if(s->hid_pair>0&&s->hid_slot>=2)s->hid418=1; else if(s->hid_pair==0||s->hid_slot==1)s->hid418=0;
    rtw_cx_link(s); return 1; }
static int rtw_cx_algo(const rtw_cx_st* s){
    if(s->a2dp&&!s->pan&&!s->hid&&!s->hfp&&!s->multi)return CX_BT_A2DP;
    if((s->hid||s->hfp)&&!s->a2dp&&!s->pan)return CX_BT_HID;
    if(!s->prof_n)return CX_BT_IDLE;
    return CX_BT_OTHER; }
static int rtw_cx_decide(const rtw_cx_st* s,u8* tab,u16* tdma){
    u8 t=1; u16 d=0; int c;
    if(!s->bt_on){ c=s->wl_conn?CX_WL_ONLY:CX_WL_NOTCONN; t=s->wl_conn?2:1; }
    else if(s->under5g){ c=CX_WL_5G; t=0; }
    else if(s->inq_page||s->host_inq){ c=CX_BT_INQ; int hi=s->wl_scan||s->wl_connecting;
        if(hi){ t=15; d=s->prof_n>0?10:(!s->bt_page?8:9); }
        else if(s->wl_busy){ t=12; if(!s->prof_n)d=18; else if(s->prof_n==1&&!s->a2dp)d=(u16)(20|RTW_CX_4SLOT); else d=(u16)(26|RTW_CX_4SLOT); }
        else if(s->wl_conn){ t=9; d=27; } else { t=1; d=0; } }
    else if((s->status==CX_BTS_NCON_IDLE||s->status==CX_BTS_CON_IDLE)&&s->wl_conn){ c=CX_BT_IDLE;
        if(!s->wl_busy){ t=10; d=3; } else if(s->status==CX_BTS_NCON_IDLE){ t=11; d=7; } else { t=12; d=7; } }
    else if(s->wl_scan||s->wl_connecting){ c=CX_WL_LINKSCAN; if(s->a2dp){ d=(u16)(11|RTW_CX_4SLOT); t=s->wl_busy?26:9; } else { t=9; d=7; } }
    else if(s->wl_conn){ c=rtw_cx_algo(s);
        if(c==CX_BT_HID){ if(s->ble){ t=27; d=9; } else if(s->a2dp_active){ t=9; d=18; } else if(s->hid418&&s->wl_busy){ t=32; d=(u16)(27|RTW_CX_4SLOT); } else { t=9; d=9; } }
        else if(c==CX_BT_A2DP){ t=s->wl_busy?12:9; d=(u16)((s->wl_connecting||!s->wl_busy?14:13)|RTW_CX_4SLOT); }
        else if(c==CX_BT_IDLE){ if(!s->wl_busy){ t=10; d=3; } else { t=12; d=7; } }
        else { t=12; d=s->a2dp?(u16)(13|RTW_CX_4SLOT):7; } }
    else { c=CX_WL_NOTCONN; t=1; d=0; }
    *tab=t; *tdma=d; return c; }
static u8 rtw_cx_slot_byte(int s4,u32 tbtt){
    if(s4&&tbtt<120)return 0xC1;
    if(tbtt<80&&tbtt>0){ u32 t=100/tbtt; if(100%tbtt)t++; return (u8)(t&0x3F); }
    if(tbtt>=180){ u32 t=tbtt/100; if(tbtt%100<=80)t--; return (u8)((t&0x3F)|0x80); }
    return 0x01; }
static void rtw_cx_chinfo(int conn,u8 cch,u8 bw,u8* o){ o[0]=0; o[1]=0; o[2]=0; if(!conn||!cch||cch<=14)return; o[1]=cch; o[2]=bw; }
static int rtw_cx_tdma_scbd(const rtw_cx_st* s){ return s->wl_busy&&!(s->a2dp&&(s->inq_remain||s->multi)); }
static int rtw_cx_busy(u32 dtx,u32 drx){ return dtx>100||drx>100; }
static int rtw_cx_nolps(const u8* p){ return (p[0]&0x10)&&!(p[0]&0x20); }
